import { fileURLToPath } from 'node:url';
import { realpathSync } from 'node:fs';
import { readConfig } from '../src/config.js';

// Configuration-only: no network calls, resource creation or secret output.
export function productionPreflight(env = process.env) {
  if (env.NODE_ENV !== 'production') throw new Error('NODE_ENV must be production.');
  const config = readConfig(env);
  if (!/^scrypt:[a-f0-9]{32}:[a-f0-9]{128}$/.test(config.adminHash))
    throw new Error('ADMIN_PASSWORD_HASH must be generated by password-hash.js.');
  if (!env.CLAMD_HOST) throw new Error('CLAMD_HOST must explicitly identify the private scanner.');
  const database = new URL(config.databaseUrl);
  if (!['postgres:', 'postgresql:'].includes(database.protocol))
    throw new Error('DATABASE_URL must use PostgreSQL.');
  if (!['require', 'verify-ca', 'verify-full'].includes(database.searchParams.get('sslmode')))
    throw new Error('DATABASE_URL must explicitly enable TLS with sslmode.');
  if (database.searchParams.get('sslmode') === 'require' &&
      database.searchParams.get('uselibpqcompat') === 'true')
    throw new Error('Database TLS must verify the server certificate.');
  return { status: 'configuration-valid', checks: 6 };
}

const normalizePath = (path) => {
  const resolved = realpathSync(path);
  return process.platform === 'win32' ? resolved.toLowerCase() : resolved;
};
if (process.argv[1] && normalizePath(process.argv[1]) === normalizePath(fileURLToPath(import.meta.url))) {
  try {
    const result = productionPreflight();
    console.log(JSON.stringify(result));
    console.log('Configuration only; service connectivity and operational acceptance remain required.');
  } catch {
    // Never echo arbitrary configuration, URLs or exceptions containing credentials.
    console.error('Production configuration failed validation. Check required values against docs/FLY-PRODUCTION.md.');
    process.exitCode = 1;
  }
}
